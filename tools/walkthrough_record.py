#!/usr/bin/env python3
"""Render a walkthrough evidence record from the receipts `run_examples.py` wrote.

The 0.1.62 record was written by hand beside its `runs.json`, which is how the article came to
point at a record for a pin two releases behind the scripts it describes. This renders the record
from the receipts instead, and with --check fails when the committed record no longer matches them
or when the article quotes a figure the logs do not contain.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EVIDENCE = ROOT / "evidence"

# Figures the article quotes from a specific script's output. Each one is checked against that
# run's log, because a per-script number in a table is exactly the kind that nobody re-reads: the
# article quoted speech.java's RTF from the 0.1.62 run for the whole of the 0.1.64 one.
QUOTED = {
    "speech": r"RTF: ([\d.]+)",
    "composite": r"Shared prefix tokens: (\d+)",
}


def pin(directory: Path) -> str:
    return directory.name.removeprefix("walkthrough-")


def render(directory: Path) -> str:
    receipts = json.loads((directory / "runs.json").read_text())
    version = pin(directory)
    rows = []
    for receipt in receipts:
        deps = "<br>".join(receipt["dependencies"]) or "-"
        rows.append(
            f"| [{receipt['script']}](../code/{receipt['script']}) | {receipt['exitCode']} | "
            f"`{deps}` | [{receipt['log']}]({directory.name}/{receipt['log']}) |")
    day = min(r["startedAt"] for r in receipts)[:10]
    failures = [r["script"] for r in receipts if r["exitCode"] != 0]
    verdict = ("Every one exited 0." if not failures
               else "These exited non-zero: " + ", ".join(failures) + ".")
    quoted = []
    for name, pattern in QUOTED.items():
        log = directory / f"{name}.log"
        if not log.exists():
            continue
        found = re.search(pattern, log.read_text())
        if found:
            quoted.append(f"- `{name}.java` reported {found.group(0)}")
    return "\n".join([
        f"# Walkthrough re-verified on ModelJars {version}",
        "",
        f"The {len(receipts)} non-keyed scripts were re-run on the {version} pins, on {day}, by",
        "`tools/run_examples.py`. " + verdict + " `fleet.java` is the fourteenth and is keyed; it is",
        "measured separately by `tools/measure_fleet.sh`, and its pairs live in",
        "`fleet-routing/runs/`.",
        "",
        "These are API demonstrations with real weights, not accuracy or throughput benchmarks.",
        "Source hashes, exact dependency lists and per-script timings are in",
        f"[runs.json]({directory.name}/runs.json); the environment it ran under is in",
        f"[environment.json]({directory.name}/environment.json).",
        "",
        "Figures this run produced that the article quotes:",
        "",
        *quoted,
        "",
        "| Script | Exit | Dependencies | Output |",
        "| --- | --- | --- | --- |",
        *rows,
        "",
        "This file is generated by `tools/walkthrough_record.py`; edit the receipts, not the table.",
        "",
    ])


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("directory", type=Path, nargs="?",
                        help="an evidence/walkthrough-<pin> directory; "
                             "default is the newest one that has receipts")
    parser.add_argument("--check", action="store_true",
                        help="fail instead of writing, and check the article's quoted figures")
    args = parser.parse_args()

    if args.directory:
        directory = args.directory.resolve()
    else:
        # The pin the scripts resolve today, not the newest directory: these names sort
        # lexicographically, so 0.4.3 (a Models pin, from an older record) outranks 0.1.64.
        current = re.search(r"//DEPS org\.modeljars:modeljars:(\S+)",
                            (ROOT / "code/fleet.java").read_text()).group(1)
        directory = EVIDENCE / f"walkthrough-{current}"
        if not (directory / "runs.json").exists():
            raise SystemExit(
                f"the scripts are pinned to modeljars:{current} and "
                f"evidence/{directory.name}/runs.json does not exist; re-run "
                f"tools/run_examples.py --output evidence/{directory.name}")

    body = render(directory)
    record = EVIDENCE / f"{directory.name}.md"
    if not args.check:
        record.write_text(body)
        print(f"wrote {record.relative_to(ROOT)} from {len(json.loads((directory / 'runs.json').read_text()))} receipts")
        return 0

    failures = []
    if not record.exists() or record.read_text() != body:
        failures.append(f"{record.relative_to(ROOT)} does not match {directory.name}/runs.json")
    article = " ".join((ROOT / "article.md").read_text().split())
    if f"evidence/{record.name}" not in article:
        failures.append(f"article.md does not link {record.name}; it links an older record")
    for name, pattern in QUOTED.items():
        log = directory / f"{name}.log"
        if not log.exists():
            continue
        found = re.search(pattern, log.read_text())
        if found and found.group(1) not in article:
            failures.append(
                f"article.md does not state {name}.java's measured {found.group(0)!r}")
    if failures:
        for failure in failures:
            print(f"  {failure}")
        return 1
    print(f"PASS: {record.name} matches its receipts and the article quotes this run")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
